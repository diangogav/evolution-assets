// Writes one script stub per alternate-art row of rush/RD MDPro4 Alternate.cdb.
//
// The duel engine only reuses an alias's script when the two ids are within
// the artwork offset; every row of that cdb aliases a mycard card far outside
// it, so the engine looks for rush/script/c<rowid>.lua, finds nothing and
// plays the card as a vanilla monster.
//
// The stub is the idiom mycard's own alternate cards use (276 of them ship in
// the pack): `RD.AlternateCard(<base id>)`, which loads c<base id>.lua from
// inside the alternate card's own load. The engine leaves `self_table` and
// `self_code` bound to the alternate card at that point, so the base script's
// `GetID()` yields the alternate's table and code and its effects register on
// the alternate. The only observable difference from the original is that
// `aux.Stringid(m, n)` resolves against the alternate's id, so the prompt
// strings come from the alternate's own texts row.
//
// Generated files carry GENERATED_MARKER as their first line. The generator
// rewrites those, deletes the ones whose row is gone, and never touches a
// script without the marker.

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const GENERATED_MARKER = "-- generated by scripts/build-rush-alternate-scripts.mjs; do not edit";

const CDB_PATH = "rush/RD MDPro4 Alternate.cdb";
const SCRIPT_DIR = "rush/script";
// An alias closer than this is the engine's own artwork-offset case.
const NEAR_ALIAS_DISTANCE = 20;
const CARD_SCRIPT = /^c(\d+)\.lua$/;

function stubContents({ alias, name }) {
	const title = String(name ?? "").replace(/\s+/g, " ").trim();
	return [
		GENERATED_MARKER,
		`-- Alternate artwork of ${title === "" ? "an unnamed card" : title} (${alias})`,
		`RD.AlternateCard(${alias})`,
		"",
	].join("\n");
}

/**
 * Plans the stubs for `rows` ({ id, alias, name }) against `existing`, a Map of
 * script file name → contents for everything under rush/script.
 *
 * Returns the stubs to write, the rows skipped (with why), and the generated
 * stubs left without a row.
 */
export function alternateStubs(rows, existing) {
	const candidates = rows.filter((row) => row.alias !== 0 && Math.abs(row.alias - row.id) >= NEAR_ALIAS_DISTANCE);
	const rowFiles = new Set(candidates.map((row) => `c${row.id}.lua`));
	const isGenerated = (fileName) => existing.get(fileName)?.startsWith(GENERATED_MARKER) === true;

	const skipped = [];
	const pending = [];
	for (const row of candidates) {
		const own = `c${row.id}.lua`;
		if (existing.has(own) && !isGenerated(own)) {
			skipped.push({ id: row.id, alias: row.alias, reason: "hand-written-script" });
		} else {
			pending.push(row);
		}
	}

	// A base that is itself a row resolves once its own base does, so iterate
	// until a pass settles nothing new. Generated files never count as bases on
	// their own: they are rederived from their rows or removed as stale.
	const stubs = [];
	let remaining = pending;
	let settled = true;
	const resolvable = new Set([...existing.keys()].filter((name) => !isGenerated(name)));
	while (settled) {
		settled = false;
		const next = [];
		for (const row of remaining) {
			if (resolvable.has(`c${row.alias}.lua`)) {
				stubs.push({ fileName: `c${row.id}.lua`, contents: stubContents(row) });
				resolvable.add(`c${row.id}.lua`);
				settled = true;
			} else {
				next.push(row);
			}
		}
		remaining = next;
	}
	for (const row of remaining) {
		skipped.push({ id: row.id, alias: row.alias, reason: "missing-base-script" });
	}

	const stale = [...existing.keys()]
		.filter((fileName) => CARD_SCRIPT.test(fileName) && isGenerated(fileName) && !rowFiles.has(fileName))
		.sort();
	return { stubs, skipped, stale };
}

function readRows(cdbPath) {
	const out = execFileSync(
		"sqlite3",
		[
			cdbPath,
			"SELECT json_group_array(json_object('id',d.id,'alias',d.alias,'name',t.name)) " +
				"FROM datas d LEFT JOIN texts t ON t.id=d.id ORDER BY d.id;",
		],
		{ encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
	).trim();
	return out === "" ? [] : JSON.parse(out);
}

function readScripts(dir) {
	const scripts = new Map();
	for (const fileName of readdirSync(dir)) {
		if (CARD_SCRIPT.test(fileName)) scripts.set(fileName, readFileSync(join(dir, fileName), "utf8"));
	}
	return scripts;
}

/** Runs the generator against the repository's committed files. */
export function generateAlternateScripts({ cdbPath = CDB_PATH, scriptDir = SCRIPT_DIR } = {}) {
	if (!existsSync(cdbPath)) throw new Error(`${cdbPath} is missing`);
	mkdirSync(scriptDir, { recursive: true });
	const plan = alternateStubs(readRows(cdbPath), readScripts(scriptDir));
	for (const { fileName, contents } of plan.stubs) writeFileSync(join(scriptDir, fileName), contents);
	for (const fileName of plan.stale) unlinkSync(join(scriptDir, fileName));
	return plan;
}

if (process.argv[1]?.endsWith("build-rush-alternate-scripts.mjs")) {
	const { stubs, skipped, stale } = generateAlternateScripts();
	console.log(`alternate-art scripts: ${stubs.length} written, ${skipped.length} skipped, ${stale.length} removed`);
	for (const { id, alias, reason } of skipped.slice(0, 20)) console.log(`  skipped ${id} -> ${alias}: ${reason}`);
	if (skipped.length > 20) console.log(`  ... and ${skipped.length - 20} more`);
}
